package main

import (
	"flag"
	"fmt"
	"log"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

const (
	version        = "1.6.0"
	commonFilename = "common_types.orm.go"
)

var (
	dbType       = flag.String("orm", "postgres", "Specify the ORM type (postgres, mongo, ram, skip)")
	packageName  = flag.String("pkg", "", "Specify the Go package name for the generated files")
	filter       = flag.String("filter", "", "Specify the filter type for the ORM (optional)")
	commonEnable = flag.Bool("common", false, "Enable the common types file")
	commonPath   = flag.String("common_path", "", "Specify the path for the common types file")

	filterMap = map[string]struct{}{}
)

func main() {
	log.Println("protoc-go-orm version", version, "is called")

	flag.Parse()

	// The main function runs the plugin.
	protogen.Options{
		ParamFunc: flag.CommandLine.Set,
	}.Run(func(gen *protogen.Plugin) error {
		log.Println("Running with protoc version:", protocVersion(gen))
		log.Printf("Generating ORM for: %s", *dbType)

		// Convert the filter string into a map for quick lookup
		if *filter != "" {
			for name := range strings.SplitSeq(*filter, ";") {
				filterMap[name] = struct{}{}
			}
		}

		for _, file := range gen.Files {
			if !file.Generate {
				continue
			}

			// We can generate the common types file or use domain types
			if *commonEnable {
				generateCommonFile(gen, file) // Generate the common types file
			} else {
				useCommonFile(gen, file) // Use the common types file
			}

			// Generate ORM
			err := generateFile(gen, file)
			if err != nil {
				log.Fatal(err)
			}
		}

		return nil
	})
}

func protocVersion(gen *protogen.Plugin) string {
	ver := gen.Request.GetCompilerVersion()
	if ver == nil {
		return "(unknown)"
	}

	var suffix string
	if s := ver.GetSuffix(); s != "" {
		suffix = "-" + s
	}

	return fmt.Sprintf("v%d.%d.%d%s", ver.GetMajor(), ver.GetMinor(), ver.GetPatch(), suffix)
}

func generateFile(gen *protogen.Plugin, file *protogen.File) error {
	switch *dbType {
	case "postgres":
		generatePostgresFile(gen, file)
	case "mongo":
		generateMongoFile(gen, file)
	case "ram":
		generateRAMFile(gen, file)
	case "skip":
		return nil
	default:
		return NotSupportDatabaseError{DbType: *dbType}
	}

	return nil
}

func printHeader(gen *protogen.Plugin, genFile *protogen.GeneratedFile, file *protogen.File) {
	genFile.P("// Code generated by protoc-gen-go-orm. DO NOT EDIT.")
	genFile.P("// versions:")
	genFile.P("// - protoc-gen-go-orm v" + version)
	genFile.P("// - protoc             ", protocVersion(gen))
	genFile.P("// source: ", file.Desc.Path())
	genFile.P()
	genFile.P("package ", *packageName)
	genFile.P()
}
